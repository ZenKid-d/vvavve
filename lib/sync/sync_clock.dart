/// Монотонные метки времени для слияния.
///
/// Слияние разрешает конфликты по `updatedAt`, а системные часы умеют идти
/// назад (коррекция NTP, смена часового пояса вручную). Запись, помеченная
/// временем «раньше уже отправленного», навсегда осталась бы невидимой для
/// отправщика — он считает грязным всё, что новее водяного знака. Поэтому
/// метка никогда не убывает: если часы отстали, берём предыдущую + 1 мс.
class SyncClock {
  SyncClock._();

  static int _last = 0;

  /// Текущее время в epoch ms, строго больше предыдущего выданного.
  static int now() {
    final wall = DateTime.now().millisecondsSinceEpoch;
    _last = wall > _last ? wall : _last + 1;
    return _last;
  }

  /// Учитывает уже существующие метки (например, прочитанные с диска), чтобы
  /// после перезапуска не выдать значение меньше сохранённого.
  static void seen(int stamp) {
    if (stamp > _last) _last = stamp;
  }
}
