/// Детерминированная «подпись» строки для визуальных вариаций (оттенок диска,
/// фаза переливов и т.п.).
///
/// Почему не [String.hashCode]: Dart не гарантирует одно и то же значение между
/// запусками VM, поэтому выведенный из него цвет менялся бы после каждого
/// перезапуска приложения. Здесь FNV-1a (32 бита) — одна и та же строка всегда
/// даёт одно и то же число, на любом устройстве и после обновления.
int stableSeedHash(String s) {
  var h = 0x811C9DC5;
  for (final unit in s.codeUnits) {
    // Мешаем оба байта code unit — иначе кириллица и латиница схлопывались бы
    // в младший байт и давали одинаковые хеши.
    h = ((h ^ (unit & 0xFF)) * 0x01000193) & 0xFFFFFFFF;
    h = ((h ^ ((unit >> 8) & 0xFF)) * 0x01000193) & 0xFFFFFFFF;
  }
  return h;
}

/// Оттенок 0..360 из [stableSeedHash] — для HSL/HSV-цветов.
double seedHue(String s) => (stableSeedHash(s) % 360).toDouble();
