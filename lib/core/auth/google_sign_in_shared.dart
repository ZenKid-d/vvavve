import 'package:google_sign_in/google_sign_in.dart';

/// Единственный на приложение экземпляр `GoogleSignIn`.
///
/// Их не должно быть два: экземпляры делят один аккаунт под капотом, поэтому
/// `signOut()` на одном незаметно ломает другой, а `currentUser`/`signInSilently`
/// начинают гонять состояние друг у друга. Раньше свой экземпляр держал импорт
/// лайков YouTube — теперь оба (вход в аккаунт и импорт) берут этот.
///
/// Скоупов здесь намеренно нет: `youtube.readonly` — чувствительный, и его
/// запрос при обычном входе потребовал бы верификации приложения у Google.
/// Импорт запрашивает его сам, непосредственно перед обращением к API.
final GoogleSignIn sharedGoogleSignIn = GoogleSignIn(scopes: const []);
